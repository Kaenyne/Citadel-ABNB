def test_expected_metric_guard_rejects_a_shortened_comparable_history(tmp_path):
    """Catch silent publication when the required n=16 composite history changes."""
    builder = load_builder()
    shortened = tmp_path / "shortened.csv"

    with ACTIVITY_PANEL.open(newline="", encoding="utf-8") as source:
        rows = list(csv.DictReader(source))
        fieldnames = list(rows[0])
    removed_prediction_id = next(
        row["prediction_id"]
        for row in rows
        if row["feature_id"] == "US_EMEA_REVENUE_WEIGHTED_COMPOSITE"
        and row["guidance_yoy_growth"]
    )
    kept = [row for row in rows if row["prediction_id"] != removed_prediction_id]
    with shortened.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(kept)

    metrics = builder.compute_metrics(REACTION_WORKBOOK, shortened)
    with pytest.raises(ValueError, match="activity_to_guidance.n"):
        builder.validate_expected_metrics(metrics)


def test_build_assets_emits_auditable_metrics_and_vector_figures(tmp_path):
    """Catch missing audit output or rasterized/non-PDF chart regressions."""
    builder = load_builder()

    builder.build_assets(REACTION_WORKBOOK, ACTIVITY_PANEL, tmp_path)

    audit = json.loads((tmp_path / "metrics.json").read_text(encoding="utf-8"))
    assert audit["evidence_cutoff"] == "2026-09-03"
    assert audit["metrics"]["activity_to_guidance"]["n"] == 16
    assert len(audit["inputs"]) == 4
    assert all(len(item["sha256"]) == 64 for item in audit["inputs"])
    assert (tmp_path / "metrics.tex").read_text(encoding="ascii").startswith(
        "% Generated by build_assets.py"
    )
    for figure_name in (
        "correlation_contrast.pdf",
        "guidance_vs_stock_performance.pdf",
        "event_excess_returns.pdf",
    ):
        assert (tmp_path / figure_name).read_bytes().startswith(b"%PDF-")
