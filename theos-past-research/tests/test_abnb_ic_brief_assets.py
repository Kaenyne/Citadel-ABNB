def load_builder():
    spec = importlib.util.spec_from_file_location("abnb_ic_brief_assets", BUILDER_PATH)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


